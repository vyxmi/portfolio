// Rows are noticeably taller than they are wide in a monospace grid at the
// line-height AsciiFlower renders with — without correcting for it, the
// sampled point cloud reads squashed/stretched relative to the 2D flower
// already on the page.
export const TEMPLATE_ROW_ASPECT = 1.8;

const BLANK = "⠀";

// Braille glyphs encode up to 8 raised dots in the low byte of
// (codepoint - 0x2800); popcount of that gives a cheap 1-8 "ink density"
// per glyph, used to weight sampling so denser glyphs (fuller petals) draw
// more particles than sparse ones (thin outline strokes).
function brailleDots(ch: string): number {
  const code = ch.codePointAt(0) ?? 0x2800;
  let bits = code - 0x2800;
  if (bits < 0 || bits > 0xff) return 4;
  let count = 0;
  while (bits) {
    count += bits & 1;
    bits >>= 1;
  }
  return Math.max(1, count);
}

export interface TemplateCell {
  col: number;
  row: number;
  weight: number;
}

export function buildTemplateCells(): { cells: TemplateCell[]; cols: number; rows: number } {
  const rows = FLOWER_ROWS.length;
  let cols = 0;
  const cells: TemplateCell[] = [];
  FLOWER_ROWS.forEach((line, row) => {
    const chars = [...line];
    cols = Math.max(cols, chars.length);
    chars.forEach((ch, col) => {
      if (ch === BLANK) return;
      cells.push({ col, row, weight: brailleDots(ch) });
    });
  });
  return { cells, cols, rows };
}
